import type { Draw, Game } from './types';
// 初回表示用の擬似履歴。運用開始後は公式最新結果を追加して分析します。
const n3 = ['830','146','507','992','318','640','275','481','063','719','354','886','120','437','561','904','238','675','391','742'];
const n4 = ['3816','5209','7742','1063','9451','2688','4307','6912','0574','8230','3149','7605','1826','4993','6351','2078','8514','9720','3466','5182'];
export function seedDraws(game: Game): Draw[] {
  const src = game === 'numbers3' ? n3 : n4;
  return src.map((number,i)=>({game,round:7000-i,date:'初期データ',number,source:'seed'}));
}
